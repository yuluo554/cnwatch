"""Loading and validating the frozen rule package.

The package is generated by ``tools/gen_rules.py`` and must never be edited by
hand, so this module treats any structural surprise as a fatal input error:
missing file, unreadable JSON, a category set that is not the bundled 26, a
patch table that is not the documented four in the documented order. Every one
of those raises ``UsageError`` *before* the caller opens the database, which is
what makes "exit 2 and nothing written" true rather than aspirational (K11,
plan/04 3.6).

Validation is deliberately eager and total: validating lazily would let a
package that is missing one category classify the rows before the missing
category was ever consulted.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from ..errors import UsageError

RULES_RELPATH = Path("rules") / "rules-v1.json"
ENUM_RELPATH = Path("official-categories.json")
SUPPORTED_FORMAT = "cnwatch.rules"
SUPPORTED_FORMAT_VERSION = 1
EXPECTED_CATEGORY_COUNT = 26
EXPECTED_PATCH_IDS = ("lawsuit", "reduction", "buyback", "pledge")
RISK_LEVELS = ("high", "mid", "low")

RiskBucket = Dict[str, str]


@dataclass(frozen=True)
class CategoryRule:
    id: str
    name: str
    priority: int
    patterns: Tuple[str, ...]
    neutralizers: Tuple[str, ...]


@dataclass(frozen=True)
class PatchRule:
    id: str
    name: str
    order: int
    patterns: Tuple[str, ...]
    negations: Tuple[str, ...]
    neutralizers: Tuple[str, ...]


@dataclass(frozen=True)
class RulePackage:
    rules_version: str
    categories: Tuple[CategoryRule, ...]
    match_order: Tuple[CategoryRule, ...]
    patches: Tuple[PatchRule, ...]
    risk_by_id: RiskBucket
    default_risk: str
    title_limit: int
    source_path: Path

    def risk_of(self, rule_id: str) -> str:
        return self.risk_by_id.get(rule_id, self.default_risk)

    def category(self, category_id: str) -> Optional[CategoryRule]:
        for rule in self.categories:
            if rule.id == category_id:
                return rule
        return None


class RulePackageError(UsageError):
    """The shipped rule package is missing or unusable. Nothing may be written."""


def default_resources_dir() -> Path:
    return Path(__file__).resolve().parents[1] / "resources"


def rules_path(resources_dir: Optional[Path] = None) -> Path:
    root = Path(resources_dir) if resources_dir is not None else default_resources_dir()
    return root / RULES_RELPATH


def enum_path(resources_dir: Optional[Path] = None) -> Path:
    root = Path(resources_dir) if resources_dir is not None else default_resources_dir()
    return root / ENUM_RELPATH


def _read_json(path: Path) -> dict:
    if not path.is_file():
        raise RulePackageError(
            "rule package is missing: %s" % path,
            hint="reinstall cnwatch, or regenerate it with `tools/gen_rules.py`",
        )
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise RulePackageError("rule package %s is unreadable: %s" % (path, exc))
    if not isinstance(payload, dict):
        raise RulePackageError("rule package %s is not a JSON object" % path)
    return payload


def load_enum_ids(resources_dir: Optional[Path] = None) -> List[str]:
    payload = _read_json(enum_path(resources_dir))
    categories = payload.get("categories")
    if not isinstance(categories, list) or not categories:
        raise RulePackageError("official-categories.json has no categories list")
    return [str(row["id"]) for row in categories]


def _require(payload: dict, key: str, kind) -> object:
    value = payload.get(key)
    if not isinstance(value, kind):
        raise RulePackageError("rule package field %r has the wrong shape" % key)
    return value


def _strings(raw, field_name: str) -> Tuple[str, ...]:
    if not isinstance(raw, list) or not all(isinstance(item, str) and item for item in raw):
        raise RulePackageError("rule package field %r must be a list of strings" % field_name)
    return tuple(raw)


def _categories(payload: dict) -> Tuple[CategoryRule, ...]:
    rows = _require(payload, "official_categories", list)
    seen = set()
    parsed = []
    for row in rows:
        if not isinstance(row, dict):
            raise RulePackageError("official_categories entries must be objects")
        try:
            category_id = str(row["id"])
            name = str(row["name"])
            priority = int(row["priority"])
        except (KeyError, TypeError, ValueError):
            raise RulePackageError("official category entry is incomplete: %r" % (row,))
        if category_id in seen:
            raise RulePackageError("duplicate official category id %r" % category_id)
        seen.add(category_id)
        parsed.append(
            CategoryRule(
                id=category_id,
                name=name,
                priority=priority,
                patterns=_strings(row.get("patterns"), "%s.patterns" % category_id),
                neutralizers=_strings(row.get("neutralizers", []), "%s.neutralizers" % category_id),
            )
        )
    return tuple(parsed)


def _patches(payload: dict) -> Tuple[PatchRule, ...]:
    rows = _require(payload, "keyword_patches", list)
    parsed = []
    for row in rows:
        if not isinstance(row, dict):
            raise RulePackageError("keyword_patches entries must be objects")
        try:
            patch_id = str(row["id"])
            name = str(row["name"])
            order = int(row["order"])
        except (KeyError, TypeError, ValueError):
            raise RulePackageError("keyword patch entry is incomplete: %r" % (row,))
        parsed.append(
            PatchRule(
                id=patch_id,
                name=name,
                order=order,
                patterns=_strings(row.get("patterns"), "%s.patterns" % patch_id),
                negations=_strings(row.get("negations", []), "%s.negations" % patch_id),
                neutralizers=_strings(row.get("neutralizers", []), "%s.neutralizers" % patch_id),
            )
        )
    return tuple(sorted(parsed, key=lambda rule: rule.order))


def _risk_bucket(payload: dict) -> Tuple[RiskBucket, str]:
    risk = _require(payload, "risk", dict)
    bucket: RiskBucket = {}
    for level in ("high", "mid"):
        for rule_id in _strings(risk.get(level), "risk.%s" % level):
            if rule_id in bucket:
                raise RulePackageError(
                    "risk level for %r is declared twice" % rule_id
                )
            bucket[rule_id] = level
    default = str(risk.get("default", ""))
    if default not in RISK_LEVELS:
        raise RulePackageError("risk.default must be one of %s" % (RISK_LEVELS,))
    return bucket, default


def _declared_match_policy(payload: dict) -> None:
    """The package states its own matching contract; the engine must match it."""

    match = _require(payload, "match", dict)
    if match.get("announcement_type_used") is not False:
        raise RulePackageError(
            "the rule package must declare announcement_type_used=false (K12)"
        )
    if match.get("title_only") is not True:
        raise RulePackageError("the rule package must declare title_only=true")


def load_rule_package(
    resources_dir: Optional[Path] = None,
    title_limit: int = 500,
) -> RulePackage:
    """Load, validate and freeze the package. Raises ``UsageError`` on any defect."""

    path = rules_path(resources_dir)
    payload = _read_json(path)

    if payload.get("format") != SUPPORTED_FORMAT:
        raise RulePackageError(
            "rule package format is %r, expected %r"
            % (payload.get("format"), SUPPORTED_FORMAT)
        )
    if int(payload.get("format_version", -1)) != SUPPORTED_FORMAT_VERSION:
        raise RulePackageError(
            "rule package format_version is %r; this build supports %d"
            % (payload.get("format_version"), SUPPORTED_FORMAT_VERSION)
        )

    categories = _categories(payload)
    patches = _patches(payload)
    risk_by_id, default_risk = _risk_bucket(payload)
    _declared_match_policy(payload)

    if len(categories) != EXPECTED_CATEGORY_COUNT:
        raise RulePackageError(
            "rule package has %d official categories, expected %d"
            % (len(categories), EXPECTED_CATEGORY_COUNT)
        )

    # The bundled enum table is the second copy of the same truth; comparing the
    # sets here means a package regenerated against a changed enum cannot slip
    # through on count alone.
    enum_ids = load_enum_ids(resources_dir)
    if len(enum_ids) != EXPECTED_CATEGORY_COUNT:
        raise RulePackageError(
            "official-categories.json has %d ids, expected %d"
            % (len(enum_ids), EXPECTED_CATEGORY_COUNT)
        )
    declared = {rule.id for rule in categories}
    if declared != set(enum_ids):
        raise RulePackageError(
            "rule package ids differ from the bundled enum: missing=%s extra=%s"
            % (sorted(set(enum_ids) - declared), sorted(declared - set(enum_ids)))
        )

    patch_ids = tuple(rule.id for rule in patches)
    if patch_ids != EXPECTED_PATCH_IDS:
        raise RulePackageError(
            "keyword patches are %s, expected %s in that order"
            % (list(patch_ids), list(EXPECTED_PATCH_IDS))
        )
    for rule in categories:
        if not rule.patterns:
            raise RulePackageError("official category %r has no patterns" % rule.id)
    for rule in patches:
        if not rule.patterns:
            raise RulePackageError("keyword patch %r has no patterns" % rule.id)

    unknown_risk_ids = sorted(set(risk_by_id) - declared - set(patch_ids))
    if unknown_risk_ids:
        raise RulePackageError(
            "risk table names rules that do not exist: %s" % unknown_risk_ids
        )

    version = payload.get("rules_version")
    if not isinstance(version, str) or not version.strip():
        raise RulePackageError("rule package has no rules_version")

    # Matching order is *derived* from the declared priorities rather than
    # trusted from file order: the package is stored in enum order for human
    # readability, and reading it in file order would classify 年报 before
    # 半年报 (every 半年度报告 also contains 年度报告).
    match_order = tuple(sorted(categories, key=lambda rule: (rule.priority, rule.id)))

    return RulePackage(
        rules_version=version.strip(),
        categories=categories,
        match_order=match_order,
        patches=patches,
        risk_by_id=risk_by_id,
        default_risk=default_risk,
        title_limit=int(title_limit),
        source_path=path,
    )
